export const MESSAGES = { "zh-CN": ZH, en: EN };

let locale = readStoredLocale();

export function normalizeLocale(value) {
  return value === "en" || value === "zh-CN" ? value : null;
}

export function currentLocale() {
  return locale;
}

export function setLocale(next) {
  const normalized = normalizeLocale(next);
  if (!normalized) return false;
  const changed = normalized !== locale;
  locale = normalized;
  writeStoredLocale(normalized);
  publish();
  if (typeof document !== "undefined") {
    document.documentElement.lang = normalized;
    document.documentElement.setAttribute("data-locale", normalized);
    applyI18n(document);
    document.documentElement.classList.add("i18n-ready");
    if (changed) {
      document.dispatchEvent(new CustomEvent("smsinbox:locale", { detail: { locale: normalized } }));
    }
  }
  return true;
}

// Server locale wins after login. Same value only refreshes the mirror.
export function adoptLocale(value) {
  const normalized = normalizeLocale(value);
  if (!normalized) return false;
  writeStoredLocale(normalized);
  if (normalized === locale) return false;
  return setLocale(normalized);
}

export function t(key, params) {
  const primary = MESSAGES[locale] || MESSAGES["zh-CN"];
  let text = primary[key];
  if (text == null) text = MESSAGES["zh-CN"][key];
  if (text == null) return String(key);
  if (!params) return text;
  return text.replace(/\{(\w+)\}/g, (token, name) => {
    if (!Object.prototype.hasOwnProperty.call(params, name) || params[name] == null) return token;
    return String(params[name]);
  });
}

export function applyI18n(root) {
  if (typeof document !== "undefined") {
    document.documentElement.lang = locale;
    document.documentElement.setAttribute("data-locale", locale);
    document.documentElement.classList.add("i18n-ready");
  }
  const scopes = [];
  const top = root && typeof root.querySelectorAll === "function" ? root : typeof document !== "undefined" ? document : null;
  if (!top) return;
  scopes.push(top);
  if (typeof top.querySelectorAll === "function") {
    for (const template of top.querySelectorAll("template")) {
      if (template.content) scopes.push(template.content);
    }
  }
  for (const scope of scopes) {
    const nodes = [...scope.querySelectorAll("[data-i18n], [data-i18n-attr]")];
    if (scope.nodeType === 1) nodes.unshift(scope);
    const seen = new Set();
    for (const node of nodes) {
      if (!node || seen.has(node) || node.nodeType !== 1) continue;
      seen.add(node);
      const key = node.getAttribute?.("data-i18n");
      if (key) setElementText(node, t(key));
      const spec = node.getAttribute?.("data-i18n-attr");
      if (spec) applyAttrSpec(node, spec);
    }
  }
}

export function formatRelative(ms, now = Date.now()) {
  const date = new Date(Number(ms));
  if (Number.isNaN(date.getTime())) return "";
  const diff = now - date.getTime();
  const en = locale === "en";
  if (diff >= 0 && diff < 60_000) return t("time.justNow");
  if (diff >= 0 && diff < 3_600_000) {
    const n = Math.floor(diff / 60_000);
    if (en) return new Intl.RelativeTimeFormat("en-US", { numeric: "always" }).format(-n, "minute");
    return t("time.minutesAgo", { n });
  }
  const today = new Date(now);
  const clock = en
    ? new Intl.DateTimeFormat("en-US", { hour: "numeric", minute: "2-digit" }).format(date)
    : `${pad(date.getHours())}:${pad(date.getMinutes())}`;
  if (sameDay(date, today)) return clock;
  const yesterday = new Date(today);
  yesterday.setDate(today.getDate() - 1);
  if (sameDay(date, yesterday)) return t("time.yesterdayAt", { time: clock });
  if (!en) {
    const monthDay = `${pad(date.getMonth() + 1)}-${pad(date.getDate())} ${clock}`;
    if (date.getFullYear() === today.getFullYear()) return monthDay;
    return `${date.getFullYear()}-${monthDay}`;
  }
  return new Intl.DateTimeFormat("en-US", {
    month: "short",
    day: "numeric",
    hour: "numeric",
    minute: "2-digit",
    ...(date.getFullYear() === today.getFullYear() ? {} : { year: "numeric" }),
  }).format(date);
}

export function formatMinuteStamp(ms) {
  const date = new Date(Number(ms));
  if (Number.isNaN(date.getTime())) return "";
  if (locale === "en") {
    return new Intl.DateTimeFormat("en-US", {
      year: "numeric",
      month: "short",
      day: "numeric",
      hour: "numeric",
      minute: "2-digit",
    }).format(date);
  }
  return `${date.getFullYear()}-${pad(date.getMonth() + 1)}-${pad(date.getDate())} ${pad(date.getHours())}:${pad(date.getMinutes())}`;
}

export function formatAbsoluteStamp(ms) {
  const date = new Date(Number(ms));
  if (Number.isNaN(date.getTime())) return "";
  const en = locale === "en";
  const text = date.toLocaleString(en ? "en-US" : "zh-CN", {
    hour12: en,
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
    hour: "2-digit",
    minute: "2-digit",
    second: "2-digit",
  });
  let zone = "";
  try {
    zone = Intl.DateTimeFormat().resolvedOptions().timeZone || "";
  } catch {
    zone = "";
  }
  if (!zone) return text;
  return en ? `${text} (${zone})` : `${text}（${zone}）`;
}

function setElementText(el, text) {
  const hasElementChild = [...el.childNodes].some((node) => node.nodeType === 1);
  if (!hasElementChild) {
    el.textContent = text;
    return;
  }
  const textNode = [...el.childNodes].find((node) => node.nodeType === 3 && node.textContent.trim());
  if (!textNode) {
    el.insertBefore(document.createTextNode(text), el.firstChild);
    return;
  }
  const raw = textNode.textContent;
  const lead = raw.match(/^\s*/)[0];
  const trail = raw.match(/\s*$/)[0];
  textNode.textContent = `${lead}${text}${trail}`;
}

function applyAttrSpec(el, spec) {
  for (const part of String(spec).split(";")) {
    const trimmed = part.trim();
    if (!trimmed) continue;
    const splitAt = trimmed.indexOf(":");
    if (splitAt <= 0) continue;
    const attr = trimmed.slice(0, splitAt).trim();
    const key = trimmed.slice(splitAt + 1).trim();
    if (!attr || !key) continue;
    el.setAttribute(attr, t(key));
  }
}

function pad(value) {
  return String(value).padStart(2, "0");
}

function sameDay(left, right) {
  return left.getFullYear() === right.getFullYear() && left.getMonth() === right.getMonth() && left.getDate() === right.getDate();
}

function readStoredLocale() {
  try {
    const value = localStorage.getItem(LOCALE_STORAGE_KEY);
    return normalizeLocale(value) || "zh-CN";
  } catch {
    return "zh-CN";
  }
}

function writeStoredLocale(value) {
  try {
    localStorage.setItem(LOCALE_STORAGE_KEY, value);
  } catch {
    // Private mode still keeps the choice for this view.
  }
}

function publish() {
  if (typeof window === "undefined") return;
  window.SMSINBOX_I18N = {
    MESSAGES,
    t,
    currentLocale,
    setLocale,
    adoptLocale,
    applyI18n,
    formatRelative,
  };
}

publish();
